        [Fact]
        public void AtomicWriteReplacesAndSkipsWhenUnchanged()
        {
            var dir = Path.Combine(Path.GetTempPath(), "agss-lib-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(dir);
            try
            {
                Exception err;
                var path = Path.Combine(dir, LibraryFile.FileName);
                Assert.Equal(WriteResult.Written, LibraryFile.Write(path, "{\"schema\":1,\"games\":[]}", out err));
                Assert.Equal("{\"schema\":1,\"games\":[]}", File.ReadAllText(path));
                var t0 = File.GetLastWriteTimeUtc(path);
                File.SetLastWriteTimeUtc(path, t0.AddMinutes(-5));
                Assert.Equal(WriteResult.Unchanged, LibraryFile.Write(path, "{\"schema\":1,\"games\":[]}", out err));
                Assert.Equal(t0.AddMinutes(-5), File.GetLastWriteTimeUtc(path)); // same content: not rewritten
                Assert.True(LibraryFile.WriteAtomic(path, "{\"schema\":1,\"games\":[1]}"));
                Assert.Equal("{\"schema\":1,\"games\":[1]}", File.ReadAllText(path));
                Assert.Equal(new[] { path }, Directory.GetFiles(dir));
                var r = LibraryFile.Write(Path.Combine(dir, "missing", LibraryFile.FileName), "x", out err);
                Assert.Equal(WriteResult.Failed, r);
                Assert.IsType<DirectoryNotFoundException>(err);
                Assert.False(Directory.Exists(Path.Combine(dir, "missing")), "never creates folders");
            }
            finally { Directory.Delete(dir, true); }
        }

        [Fact]
        public void OnlyTheDateDiffersMeansUnchanged()
        {
            var dir = Path.Combine(Path.GetTempPath(), "agss-lib-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(dir);
            try
            {
                Exception err;
                var path = Path.Combine(dir, LibraryFile.FileName);
                var games = SampleGames();
                Assert.Equal(WriteResult.Written, LibraryFile.Write(path, LibraryFile.ToJson(games, SampleDate), out err));
                Assert.Equal(WriteResult.Unchanged, LibraryFile.Write(path, LibraryFile.ToJson(games, SampleDate.AddDays(3)), out err));
                Assert.Contains("2026-10-29T12:00:00Z", File.ReadAllText(path));
                games[0].Name = "Celeste 2";
                Assert.Equal(WriteResult.Written, LibraryFile.Write(path, LibraryFile.ToJson(games, SampleDate.AddDays(3)), out err));
                Assert.Contains("2026-11-01T12:00:00Z", File.ReadAllText(path));
                // A lone surrogate is written as U+FFFD: the comparison is made on the written bytes, so no endless rewrite.
                var odd = LibraryFile.ToJson(new[] { new LibraryGame { Name = "Odd \uD800 name" } }, SampleDate);
                Assert.Equal(WriteResult.Written, LibraryFile.Write(path, odd, out err));
                Assert.Equal(WriteResult.Unchanged, LibraryFile.Write(path, odd, out err));
            }
            finally { Directory.Delete(dir, true); }
        }

        [Fact]
        public void TemporaryNamesAreUniqueAndConcurrentWritersLoseNothing()
        {
            var dir = Path.Combine(Path.GetTempPath(), "agss-lib-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(dir);
            try
            {
                var path = Path.Combine(dir, LibraryFile.FileName);
                var results = new System.Collections.Concurrent.ConcurrentBag<WriteResult>();
                var threads = Enumerable.Range(0, 4).Select(t => new System.Threading.Thread(() =>
                {
                    for (int i = 0; i < 50; i++) { Exception e; results.Add(LibraryFile.Write(path, "{\"schema\":1,\"games\":[" + t + "," + i + "]}", out e)); }
                })).ToList();
                threads.ForEach(t => t.Start()); threads.ForEach(t => t.Join());
                Assert.Equal(new[] { path }, Directory.GetFiles(dir)); // no leftover temporary file
                var text = File.ReadAllText(path);
                Assert.StartsWith("{\"schema\":1,\"games\":[", text);
                Assert.EndsWith("]}", text);
                Assert.True(results.Count(r => r == WriteResult.Written) >= 4, "each writer gets through at least once");
            }
            finally { Directory.Delete(dir, true); }
        }

        [Fact]
        public void DeleteRemovesOnlyTheListFile()
        {
            var dir = Path.Combine(Path.GetTempPath(), "agss-lib-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(dir);
            try
            {
                Exception err;
                var other = Path.Combine(dir, "status.json");
                File.WriteAllText(other, "{}");
                Assert.False(LibraryFile.Delete(other, out err), "never another file");
                Assert.True(File.Exists(other));
                var path = Path.Combine(dir, LibraryFile.FileName);
                Assert.False(LibraryFile.Delete(path, out err), "nothing to delete");
                File.WriteAllText(path, "{}");
                Assert.True(LibraryFile.Delete(path, out err));
                Assert.False(File.Exists(path));
                Assert.Null(err);
            }
            finally { Directory.Delete(dir, true); }
        }
